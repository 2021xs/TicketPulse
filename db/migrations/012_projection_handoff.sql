-- M4-03B adds candidate handoff/progress only. ACTIVE bindings and CDC stay intact.
CREATE TABLE IF NOT EXISTS sync_projection_handoffs (
    handoff_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    version_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    contract_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    job_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    freeze_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    freeze_revision BIGINT NOT NULL,
    phase VARCHAR(16) NOT NULL,
    pinned_offsets JSON NULL,
    final_marker VARCHAR(64) NULL,
    final_report JSON NULL,
    final_report_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    es_group VARCHAR(384) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ck_group VARCHAR(384) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    verification_marker VARCHAR(64) NULL,
    verification_report JSON NULL,
    verification_report_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    revision BIGINT NOT NULL DEFAULT 1,
    last_error VARCHAR(1024) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    verified_at DATETIME(6) NULL,
    UNIQUE KEY uk_handoff_version(version_id),
    UNIQUE KEY uk_handoff_job(job_id),
    FOREIGN KEY(version_id) REFERENCES sync_projection_versions(version_id),
    FOREIGN KEY(job_id) REFERENCES sync_rebuild_jobs(job_id),
    CHECK (phase IN ('DRAINING','PINNED','OFFSETS_READY','CONSUMING','VERIFIED')),
    CHECK (freeze_revision>0 AND revision>0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_handoff_partitions (
    handoff_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    component VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    partition_id INT NOT NULL,
    initial_offset BIGINT NULL,
    confirmed_at DATETIME(6) NULL,
    verification_offset BIGINT NULL,
    PRIMARY KEY(handoff_id,component,partition_id),
    FOREIGN KEY(handoff_id) REFERENCES sync_projection_handoffs(handoff_id),
    CHECK (component IN ('es','ck')),
    CHECK (partition_id>=0 AND (initial_offset IS NULL OR initial_offset>=0))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_target_owners (
    target_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    component VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_kind VARCHAR(16) NOT NULL,
    owner_id VARCHAR(384) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_epoch BIGINT NOT NULL,
    handoff_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    version_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    worker_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    worker_host VARCHAR(255) NULL,
    worker_pid BIGINT NULL,
    lock_connection_id BIGINT NULL,
    updated_at DATETIME(6) NOT NULL,
    CHECK (component IN ('es','ck')),
    CHECK (owner_kind IN ('rebuild_job','sealed','consumer_group')),
    CHECK (owner_epoch>0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_handoff_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    handoff_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    operation VARCHAR(64) NOT NULL,
    details JSON NOT NULL,
    occurred_at DATETIME(6) NOT NULL,
    KEY idx_handoff_log(handoff_id,id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_deliveries (
    version_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    component VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    topic VARCHAR(249) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    partition_id INT NOT NULL,
    record_offset BIGINT NOT NULL,
    event_id VARCHAR(255) NOT NULL,
    ticket_id BIGINT NULL,
    ticket_version BIGINT NULL,
    status VARCHAR(32) NOT NULL,
    attempts INT UNSIGNED NOT NULL,
    first_seen_at DATETIME(6) NOT NULL,
    last_seen_at DATETIME(6) NOT NULL,
    event_at DATETIME(6) NULL,
    last_error VARCHAR(1024) NULL,
    isolated_payload MEDIUMBLOB NULL,
    recovery_partition INT NULL,
    recovery_offset BIGINT NULL,
    PRIMARY KEY(version_id,component,topic,partition_id,record_offset),
    KEY idx_projection_delivery_status(version_id,component,status,last_seen_at),
    KEY idx_projection_delivery_event(version_id,component,event_id,partition_id),
    FOREIGN KEY(version_id) REFERENCES sync_projection_versions(version_id),
    CHECK (component IN ('es','ck') AND partition_id>=0 AND record_offset>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_worker_state (
    version_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    component VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    group_id VARCHAR(384) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    owner_epoch BIGINT NOT NULL,
    state VARCHAR(32) NOT NULL,
    heartbeat_at DATETIME(6) NOT NULL,
    last_event_at DATETIME(6) NULL,
    last_error VARCHAR(1024) NULL,
    member_id VARCHAR(384) NULL,
    generation INT NULL,
    PRIMARY KEY(version_id,component),
    FOREIGN KEY(version_id) REFERENCES sync_projection_versions(version_id),
    CHECK (component IN ('es','ck'))
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sync_projection_watermarks (
    version_id VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    component VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    partition_id INT NOT NULL,
    topic VARCHAR(249) NOT NULL,
    barrier_id VARCHAR(64) NOT NULL,
    issued_at DATETIME(6) NOT NULL,
    record_offset BIGINT NOT NULL,
    binlog_file VARCHAR(255) NOT NULL,
    binlog_pos BIGINT UNSIGNED NOT NULL,
    applied_at DATETIME(6) NOT NULL,
    PRIMARY KEY(version_id,component,partition_id),
    FOREIGN KEY(version_id) REFERENCES sync_projection_versions(version_id),
    CHECK (component IN ('es','ck'))
) ENGINE=InnoDB;
